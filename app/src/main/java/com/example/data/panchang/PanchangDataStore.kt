    fun entityToDevotionalEvent(entity: PanchangEventEntity, userTimezone: TimeZone = TimeZone.getDefault()): DevotionalEvent {
        val parts = entity.eventDate.split("-")
        val (dateFormatted, dayFormatted) = if (parts.size == 3) {
            val y = parts[0].toIntOrNull() ?: 2026
            val m = parts[1].toIntOrNull() ?: 1
            val d = parts[2].toIntOrNull() ?: 1
            val cal = Calendar.getInstance().apply {
                set(Calendar.YEAR, y)
                set(Calendar.MONTH, m - 1)
                set(Calendar.DAY_OF_MONTH, d)
                set(Calendar.HOUR_OF_DAY, 12)
                set(Calendar.MINUTE, 0)
                set(Calendar.SECOND, 0)
                set(Calendar.MILLISECOND, 0)
            }
            Pair(
                SimpleDateFormat("dd MMM yyyy", Locale.ENGLISH).format(cal.time),
                SimpleDateFormat("EEEE", Locale.ENGLISH).format(cal.time)
            )
        } else {
            val sdfIso = SimpleDateFormat("yyyy-MM-dd", Locale.ENGLISH).apply {
                timeZone = istTimeZone
            }
            val dateObj = try {
                sdfIso.parse(entity.eventDate) ?: Date(entity.startTimestampUtc)
            } catch (e: Exception) {
                Date(entity.startTimestampUtc)
            }
            Pair(
                SimpleDateFormat("dd MMM yyyy", Locale.ENGLISH).apply { timeZone = userTimezone }.format(dateObj),
                SimpleDateFormat("EEEE", Locale.ENGLISH).apply { timeZone = userTimezone }.format(dateObj)
            )
        }

        val idNum = kotlin.math.abs(entity.eventId.hashCode())

        return DevotionalEvent(
            id = idNum,
            nameHindi = entity.nameHindi,
            nameEnglish = entity.nameEnglish,
            dateString = dateFormatted,
            dayOfWeek = dayFormatted,
            pakshaHindi = if (entity.paksha == "SHUKLA") "शुक्ल पक्ष" else "कृष्ण पक्ष",
            pakshaEnglish = if (entity.paksha == "SHUKLA") "Shukla Paksha" else "Krishna Paksha",
            tithiHindi = entity.tithiHindi,
            tithiEnglish = entity.tithiEnglish,
            category = entity.category,
            shortDescHindi = entity.shortDescHindi,
            shortDescEnglish = entity.shortDescEnglish,
            fullDescHindi = entity.fullDescHindi,
            fullDescEnglish = entity.fullDescEnglish,
            eatHindi = entity.allowedFoodHindi,
            eatEnglish = entity.allowedFoodEnglish,
            notEatHindi = entity.forbiddenFoodHindi,
            notEatEnglish = entity.forbiddenFoodEnglish,
            gitaReference = entity.gitaReference,
            mantraHindi = entity.primaryMantraHindi,
            mantraEnglish = entity.primaryMantraEnglish,
            paranaTimeHindi = entity.paranaTimeHindi,
            paranaTimeEnglish = entity.paranaTimeEnglish,
            startTime = entity.paranaStart,
            endTime = entity.paranaEnd,
            targetTimestamp = entity.startTimestampUtc
        )
    }
