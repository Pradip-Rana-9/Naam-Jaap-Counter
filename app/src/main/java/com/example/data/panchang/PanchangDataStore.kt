    private fun parseDateToUtcMillis(dateIso: String, hourIst: Int = 5, minuteIst: Int = 30): Long {
        val sdf = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.ENGLISH).apply {
            timeZone = istTimeZone
        }
        val dateStr = String.format(Locale.ENGLISH, "%s %02d:%02d", dateIso, hourIst, minuteIst)
        return sdf.parse(dateStr)?.time ?: 0L
    }

